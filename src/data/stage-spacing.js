export function applyStageSpacing(data, stage, sub, pivot) {
  const layout=STAGE_SPACING[`${stage}-${sub}`];
  if(!layout) return data;
  for(const [kind,positions] of Object.entries(layout)){
    if(kind==='lasers' || kind==='gates'){
      for(const [index,[x1,y1,x2,y2]] of Object.entries(positions)){
        const beam=kind==='lasers'?data.lasers[index]:data.switches[index].gate;
        Object.assign(beam,{x1:pivot.x+x1,y1:pivot.y+y1,x2:pivot.x+x2,y2:pivot.y+y2});
      }
      continue;
    }
    const items=kind==='blackhole' ? (Array.isArray(data.blackhole)?data.blackhole:[data.blackhole]) : data[kind];
    for(const [index,[dx,dy]] of Object.entries(positions)){
      const item=items[index];
      item.x=pivot.x+dx;item.y=pivot.y+dy;
      if(kind==='obstacles'){item.baseX=item.x;item.baseY=item.y;}
    }
  }
  return data;
}
