const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', async route => {
      const url = new URL(route.request().url());
      if (url.hostname !== 'game.test') return route.abort();
      const file = path.join(__dirname, '..', url.pathname === '/' ? 'index.html' : url.pathname);
      let body = fs.readFileSync(file, 'utf8');
      if (url.pathname === '/src/main.js') body += '\nwindow.testRun = code => eval(code);';
      await route.fulfill({ body, contentType: file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : 'text/html' });
    });
    await page.goto('http://game.test');
    await page.waitForFunction(() => window.testRun);
    await page.evaluate(() => {
      document.getElementById('titleScreen').classList.add('hidden');
      document.getElementById('stageBriefing').classList.add('hidden');
      window.testRun('loadStage(1)');
    });
    assert.equal(await page.locator('#btnReplay').isDisabled(), true);
    await page.locator('#btnHints').click();
    await page.locator('#stageBriefing').waitFor({ state: 'visible' });
    await page.locator('#btnDismissBriefing').click();
    await page.evaluate(() => window.testRun('loadStage(stageSubToIndex(39, 2))'));
    await page.locator('#btnHints').click();
    assert.match(await page.locator('#mechanicHints').innerText(), /upward/);
    assert.match(await page.locator('#mechanicHints').innerText(), /locked/);
    await page.locator('#btnDismissBriefing').click();
    await page.locator('#btnFire').click();
    await page.waitForTimeout(350);
    await page.locator('#btnHints').click();
    assert.equal(await page.evaluate(() => window.testRun('gameStatus')), 'paused');
    await page.locator('#btnDismissBriefing').click();
    await page.locator('#btnPause').click();
    await page.waitForTimeout(250);
    await page.locator('#btnStop').click();
    assert.equal(await page.locator('#btnReplay').isEnabled(), true);
    const saved = await page.evaluate(() => JSON.stringify(localStorage));
    const state = await page.evaluate(() => window.testRun('JSON.stringify({systems,targets,timeElapsed,highScores,stageStars})'));
    await page.locator('#btnReplay').click();
    assert.equal(await page.locator('#replayDialog').isVisible(), true);
    assert.ok(Number(await page.locator('#replaySeek').getAttribute('max')) > 0);
    await page.locator('#replayPlay').click();
    await page.waitForTimeout(120);
    assert.ok(Number(await page.locator('#replaySeek').inputValue()) > 0);
    await page.locator('#replaySpeed').selectOption('2');
    await page.locator('#replaySeek').fill('0');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#replayDialog').isVisible(), false);
    assert.equal(await page.evaluate(() => JSON.stringify(localStorage)), saved);
    assert.equal(await page.evaluate(() => window.testRun('JSON.stringify({systems,targets,timeElapsed,highScores,stageStars})')), state);
    await page.locator('#btnReplay').click();
    await page.locator('#replayDialog').focus();
    await page.keyboard.press('Space');
    assert.equal(await page.evaluate(() => window.testRun('gameStatus')), 'end');
    await page.locator('#replayClose').click();
    await page.locator('#btnRetry').click();
    await page.locator('#btnFire').click();
    assert.equal(await page.locator('#btnReplay').isDisabled(), true);
    await page.waitForTimeout(150);
    await page.evaluate(() => window.testRun('timeElapsed = timeLimit'));
    await page.waitForFunction(() => window.testRun('gameStatus') === 'end');
    assert.equal(await page.locator('#btnReplay').isEnabled(), true);
    await page.locator('#btnReplay').click();
    await page.locator('#replayClose').click();
    await page.locator('#overlayBtn').click();
    await page.locator('#btnFire').click();
    await page.waitForTimeout(150);
    await page.evaluate(() => window.testRun("targets.forEach(t => t.alive = false); gameStatus = 'clearing'; clearingTimer = 3"));
    await page.waitForFunction(() => window.testRun('gameStatus') === 'end');
    assert.equal(await page.locator('#btnReplay').isEnabled(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#btnMore').click();
    await page.locator('#btnReplay').click();
    const bounds = await page.locator('#replayDialog').boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
    await page.locator('#replayClose').click();
    assert.deepEqual(errors, []);
    console.log('Hints reopen and pause gameplay; replay records stopped attempts, plays/seeks, blocks gameplay input and leaves progress unchanged.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
